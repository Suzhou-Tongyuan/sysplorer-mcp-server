"""Generate sysplorer-mcp-server/_build_meta.py from install/package_version.json and git.

- internal: full version = {version_base}.{git_commit_count}; version_display adds suffix (Internal)
- release: full version = {version_base} only (BUILD_COUNTER = 0); version_display equals version
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import re
import subprocess
import sys
from datetime import datetime
from pathlib import Path

# 手工基线仅为「主.次」数字，提交序号由 Git 单独追加；勿写成 "0.1.x" 等占位符
_VERSION_BASE_RE = re.compile(r"^\d+\.\d+$")


def _run_git(repo: Path, *args: str) -> str | None:
    try:
        out = subprocess.check_output(
            ["git", *args],
            cwd=repo,
            text=True,
            stderr=subprocess.DEVNULL,
        )
        return out.strip()
    except (subprocess.CalledProcessError, FileNotFoundError, OSError):
        return None


def git_meta(repo: Path) -> tuple[str, int]:
    short = _run_git(repo, "rev-parse", "--short", "HEAD") or "unknown"
    raw = _run_git(repo, "rev-list", "--count", "HEAD")
    try:
        count = int(raw) if raw else 0
    except ValueError:
        count = 0
    return short, count


def write_build_meta(
    *,
    repo_root: Path,
    mode: str,
    output_path: Path | None = None,
) -> tuple[str, str, int, int, str, str]:
    """Returns (version_full, version_base, build_counter, source_git_commit_count, build_time_iso, git_revision)."""
    cfg_path = repo_root / "install" / "package_version.json"
    if not cfg_path.is_file():
        raise SystemExit(f"Missing version config: {cfg_path}")
    cfg = json.loads(cfg_path.read_text(encoding="utf-8"))
    version_base = str(cfg.get("version_base", "")).strip()
    if not version_base:
        raise SystemExit("package_version.json: version_base is required")
    if not _VERSION_BASE_RE.fullmatch(version_base):
        raise SystemExit(
            'package_version.json: version_base must look like "0.1" (digits.digits only). '
            'Do not use a placeholder such as "0.1.x" — internal builds append the git commit '
            "count automatically."
        )

    git_rev, source_git_commit_count = git_meta(repo_root)
    if mode == "internal" and source_git_commit_count == 0:
        print(
            "warning: git rev-list --count HEAD is 0 (not a git repo or empty history?). "
            "Internal version will be just version_base.",
            file=sys.stderr,
        )
    build_time = datetime.now().astimezone().isoformat(timespec="seconds")

    if mode == "release":
        build_counter = 0
        version_full = version_base
    else:
        build_counter = source_git_commit_count
        version_full = f"{version_base}.{source_git_commit_count}"

    out = output_path or (repo_root / "sysplorer-mcp-server" / "_build_meta.py")
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Generated by install/write_build_meta.py — do not edit by hand.",
        f"VERSION_BASE = {version_base!r}",
        f"BUILD_COUNTER = {build_counter}",
        f"SOURCE_GIT_COMMIT_COUNT = {source_git_commit_count}",
        f"BUILD_TIME_ISO = {build_time!r}",
        f"GIT_REVISION = {git_rev!r}",
        "",
    ]
    out.write_text("\n".join(lines), encoding="utf-8")

    return version_full, version_base, build_counter, source_git_commit_count, build_time, git_rev


def load_existing_build_meta(repo_root: Path) -> dict:
    """Read sysplorer-mcp-server/_build_meta.py without re-running git (for post-build JSON)."""
    path = repo_root / "sysplorer-mcp-server" / "_build_meta.py"
    if not path.is_file():
        raise SystemExit(f"Missing _build_meta.py: {path}")
    spec = importlib.util.spec_from_file_location("_mcp_build_meta_read", path)
    if spec is None or spec.loader is None:
        raise SystemExit(f"Cannot load: {path}")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    vb = str(getattr(mod, "VERSION_BASE", "")).strip()
    bc = int(getattr(mod, "BUILD_COUNTER", 0))
    src = int(getattr(mod, "SOURCE_GIT_COMMIT_COUNT", bc))
    bt = str(getattr(mod, "BUILD_TIME_ISO", ""))
    gr = str(getattr(mod, "GIT_REVISION", ""))
    vf = f"{vb}.{bc}" if bc else vb
    if not bt:
        kind = "dev"
    elif bc > 0:
        kind = "internal"
    else:
        kind = "release"
    version_display = f"{vf}(Internal)" if kind == "internal" else vf
    return {
        "version": vf,
        "version_display": version_display,
        "version_base": vb,
        "version_core": vb,
        "build_counter": bc,
        "git_commit_count": src,
        "build_kind": kind,
        "build_time": bt,
        "git_revision": gr,
    }


def main() -> None:
    ap = argparse.ArgumentParser(description="Write _build_meta.py for MCP server packaging.")
    ap.add_argument("--repo-root", type=Path, required=True)
    ap.add_argument(
        "--mode",
        choices=("internal", "release"),
        default=None,
        help="Required unless only using --dump-mcp-json.",
    )
    ap.add_argument(
        "--output",
        type=Path,
        default=None,
        help="Path to _build_meta.py (default: <repo>/sysplorer-mcp-server/_build_meta.py)",
    )
    ap.add_argument(
        "--print-json",
        action="store_true",
        help="Print MCP_BUILD_INFO fields as one JSON object to stdout (after write).",
    )
    ap.add_argument(
        "--dump-mcp-json",
        type=Path,
        default=None,
        help="Write MCP_BUILD_INFO.json from existing sysplorer-mcp-server/_build_meta.py (no regenerate).",
    )
    args = ap.parse_args()
    repo = args.repo_root.resolve()
    if args.dump_mcp_json is not None:
        payload = load_existing_build_meta(repo)
        args.dump_mcp_json.parent.mkdir(parents=True, exist_ok=True)
        args.dump_mcp_json.write_text(
            json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        return
    if args.mode is None:
        raise SystemExit("error: --mode is required (internal|release) unless using --dump-mcp-json")
    vf, vb, bc, src_count, bt, gr = write_build_meta(
        repo_root=repo, mode=args.mode, output_path=args.output
    )
    if args.print_json:
        import json as _json

        kind = "release" if args.mode == "release" else "internal"
        version_display = f"{vf}(Internal)" if kind == "internal" else vf
        payload = {
            "version": vf,
            "version_display": version_display,
            "version_base": vb,
            "version_core": vb,
            "build_counter": bc,
            "git_commit_count": src_count,
            "build_kind": kind,
            "build_time": bt,
            "git_revision": gr,
        }
        print(_json.dumps(payload, ensure_ascii=False))
    else:
        print(vf)


if __name__ == "__main__":
    main()
